def main():
    src, dst = sys.argv[1], sys.argv[2]
    doc = Document(src)

    # 先把段落快照成列表，避免边遍历边改
    paras = list(doc.paragraphs)

    idx_400 = 0
    done = set()

    for p in paras:
        text = p.text.strip()
        if not text:
            continue

        # 三处相同的「400字内」按出现顺序处理
        if text.startswith("400字内"):
            items = ORDER_400[idx_400]
            idx_400 += 1
            _apply(doc, p, items)
            done.add(text)
            continue

        key = None
        for k in CONTENT:
            if text.startswith(k[:12]) and k not in done:
                # 需要前缀足够长以避免误匹配
                if text == k or text.startswith(k):
                    key = k
                    break
        if key is None:
            continue
        items = CONTENT[key]
        if items:
            _apply(doc, p, items)
        done.add(key)

    doc.save(dst)
    print("saved:", dst)


def _apply(doc, anchor, items):
    """在 anchor 后依次插入 items 中的段落/表格，然后删除 anchor。"""
    cur = anchor
    for kind, payload in items:
        if kind == "T":
            insert_table_after(doc, cur, payload)
            # 表格后补一个空段，便于后续排版
            cur = insert_paragraph_after(cur, "", style=doc.styles["Normal"])
        else:
            # 默认挂 Normal（模板 10.5pt 两端对齐），否则会退回 docDefaults 导致字号偏大、
            # 正文宽度超出页面被截断。
            style = doc.styles["Normal"]
            if kind == "H":
                for name in ("Heading 2", "Heading 3"):
                    try:
                        style = doc.styles[name]
                        break
                    except KeyError:
                        continue
            elif kind == "H2":
                for name in ("Heading 3", "Heading 2"):
                    try:
                        style = doc.styles[name]
                        break
                    except KeyError:
                        continue
            cur = insert_paragraph_after(cur, payload, style=style)
    anchor._p.getparent().remove(anchor._p)


if __name__ == "__main__":
    main()
